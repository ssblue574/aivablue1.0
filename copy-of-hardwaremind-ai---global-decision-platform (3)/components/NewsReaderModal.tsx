import React from 'react';
import { X, Calendar, Share2, ExternalLink, Clock, User } from 'lucide-react';
import { clsx } from 'clsx';
import { NewsItem } from '../data';
import { useTheme } from '../ThemeContext';
import { FuturisticModal } from './FuturisticModal';

interface NewsReaderModalProps {
    news: NewsItem;
    onClose: () => void;
    t: (key: any) => string;
}

export const NewsReaderModal: React.FC<NewsReaderModalProps> = ({ news, onClose, t }) => {
    const { theme } = useTheme();
    const isDark = theme === 'dark';

    // 模拟文章段落 (如果原本没有全文内容)
    const paragraphs = news.description.split('\n').filter(p => p.trim().length > 0);
    // 如果描述太短，就重复几次模拟长文效果（演示用，实际应从后端获取全文）
    const displayContent = paragraphs.length < 3 ? [...paragraphs, ...paragraphs, ...paragraphs] : paragraphs;

    return (
        <FuturisticModal
            isOpen={true}
            onClose={onClose}
            maxWidth="4xl"
            showCloseButton={false}
            closeOnBackdropClick={true}
        >
            <div className="relative w-full max-h-[85vh] overflow-y-auto flex flex-col">
                {/* Header Image */}
                <div className="relative h-64 md:h-96 flex-shrink-0">
                    <img src={news.imageUrl} alt={news.title} className="w-full h-full object-cover" />
                    <div className="absolute inset-0 bg-gradient-to-t from-black/80 to-transparent" />
                    <button 
                        onClick={onClose}
                        className="absolute top-6 right-6 p-2 rounded-full bg-black/20 text-white hover:bg-black/40 transition-colors backdrop-blur-md"
                    >
                        <X size={24} />
                    </button>
                    
                    <div className="absolute bottom-0 left-0 right-0 p-8">
                        <div className="flex items-center gap-3 text-xs font-bold uppercase tracking-[0.2em] text-[#00FFC6] mb-3">
                            <span>{news.category}</span>
                        </div>
                        <h1 className="text-3xl md:text-5xl font-bold leading-tight text-white mb-4">
                            {news.title}
                        </h1>
                        <div className="flex items-center gap-6 text-sm text-white/70">
                            <span className="flex items-center gap-1"><Calendar size={14} /> {news.date}</span>
                            <span className="flex items-center gap-1"><User size={14} /> {news.source || (t('home_date_format') === 'zh-CN' ? 'Aiva 情报' : 'AIVA Intelligence')}</span>
                            <span className="flex items-center gap-1"><Clock size={14} /> {t('home_date_format') === 'zh-CN' ? '5 分钟阅读' : '5 min read'}</span>
                        </div>
                    </div>
                </div>

                {/* Content Body */}
                <div className="p-8 md:p-12 md:px-20 space-y-8 leading-relaxed text-lg">
                    <div className={clsx("font-medium text-xl border-l-4 pl-6 py-1", isDark ? "border-[#00FFC6] text-white/90" : "border-black text-black/90")}>
                        {news.description}
                    </div>

                    {/* 模拟的正文内容 */}
                    <div className={clsx("space-y-6", isDark ? "text-white/70" : "text-black/70")}>
                        {displayContent.map((para, idx) => (
                            <p key={idx}>{para}</p>
                        ))}
                        <p>
                            (Here is where the full deep-dive content generated by AI would go. It would analyze the implications of {news.title}, compare it with market competitors, and provide strategic insights for decision makers.)
                        </p>
                        <h3 className={clsx("text-2xl font-bold mt-8 mb-4", isDark ? "text-white" : "text-black")}>Deep Analysis</h3>
                        <p>
                            Lorem ipsum dolor sit amet, consectetur adipiscing elit. Sed do eiusmod tempor incididunt ut labore et dolore magna aliqua. Ut enim ad minim veniam, quis nostrud exercitation ullamco laboris nisi ut aliquip ex ea commodo consequat.
                        </p>
                    </div>

                    {/* Action Bar */}
                    <div className={clsx("pt-12 mt-12 border-t flex items-center justify-between", isDark ? "border-white/10" : "border-black/10")}>
                        <div className="flex gap-2">
                            {news.tags?.map(tag => (
                                <span key={tag} className={clsx("px-3 py-1 rounded-full text-xs border", isDark ? "border-white/20 bg-white/5" : "border-black/10 bg-gray-100")}>
                                    #{tag}
                                </span>
                            ))}
                        </div>
                        <div className="flex gap-3">
                            <button className={clsx("p-3 rounded-full border transition-colors", isDark ? "border-white/20 hover:bg-white/10" : "border-black/10 hover:bg-black/5")}>
                                <Share2 size={20} />
                            </button>
                            {news.readMoreUrl && (
                                <a 
                                    href={news.readMoreUrl} 
                                    target="_blank" 
                                    rel="noreferrer"
                                    className={clsx("flex items-center gap-2 px-6 py-3 rounded-full font-bold text-sm transition-colors", isDark ? "bg-white text-black hover:bg-gray-200" : "bg-black text-white hover:bg-gray-800")}
                                >
                                    {t('home_read_more')} <ExternalLink size={16} />
                                </a>
                            )}
                        </div>
                    </div>
                </div>
            </div>
        </FuturisticModal>
    );
};

